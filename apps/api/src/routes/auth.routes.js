const router=require('express').Router();
const auth=require('../controllers/auth.controller');
const dashboard=require('../controllers/dashboard.controller');
const {authenticate,allow,ROLES}=require('../middleware/auth');
router.post('/auth/login',auth.login);
router.post('/auth/customer-register',auth.registerCustomer);
router.get('/auth/customer-profile',authenticate,allow(ROLES.CUSTOMER),auth.customerInfo);
router.get('/auth/me',authenticate,auth.me);
router.get('/branches',auth.branches);
router.get('/branches/:branchId/registers',authenticate,auth.registers);
router.get('/customers/lookup',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER,ROLES.CASHIER),auth.customerLookup);
router.get('/users',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER),auth.users);
router.get('/dashboard',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER,ROLES.CASHIER),dashboard.index);
const management=require('../controllers/management.controller');
router.patch('/branches/:id/status',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER),management.branchStatus);
router.get('/audit',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER),management.logs);
router.get('/reports/daily',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER),management.report);
router.post('/employees',authenticate,allow(ROLES.ADMIN,ROLES.MANAGER),management.createEmployee);
module.exports=router;
