CREATE TABLE IF NOT EXISTS branches (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(16) NOT NULL UNIQUE,
 name VARCHAR(150) NOT NULL,
 address VARCHAR(250) NOT NULL,
 latitude DECIMAL(10,7) NULL,
 longitude DECIMAL(10,7) NULL,
 opening_time TIME NOT NULL DEFAULT '07:00:00',
 closing_time TIME NOT NULL DEFAULT '22:00:00',
 status ENUM('OPEN','CLOSED','PAUSED') NOT NULL DEFAULT 'CLOSED',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 phone VARCHAR(20) NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','BRANCH_MANAGER','CASHIER','BARISTA','CUSTOMER') NOT NULL,
 branch_id BIGINT UNSIGNED NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS customer_profiles (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 points INT NOT NULL DEFAULT 0,
 tier ENUM('BRONZE','SILVER','GOLD') NOT NULL DEFAULT 'BRONZE',
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS registers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 code VARCHAR(25) NOT NULL,
 name VARCHAR(100) NOT NULL,
 UNIQUE(branch_id, code),
 FOREIGN KEY (branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS work_shifts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL,
 job_role ENUM('CASHIER','BARISTA','SERVICE') NOT NULL,
 starts_at DATETIME NOT NULL,
 ends_at DATETIME NOT NULL,
 required_staff INT NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (branch_id) REFERENCES branches(id),
 FOREIGN KEY (created_by) REFERENCES users(id),
 CHECK(ends_at > starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS shift_assignments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 shift_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 status ENUM('ASSIGNED','LEAVE','SWAPPED') NOT NULL DEFAULT 'ASSIGNED',
 UNIQUE(shift_id,user_id),
 FOREIGN KEY (shift_id) REFERENCES work_shifts(id),
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 assignment_id BIGINT UNSIGNED NOT NULL UNIQUE,
 check_in DATETIME NULL,
 check_out DATETIME NULL,
 method ENUM('GPS','QR','WIFI','MANUAL') NOT NULL DEFAULT 'MANUAL',
 late_minutes INT NOT NULL DEFAULT 0,
 early_minutes INT NOT NULL DEFAULT 0,
 status ENUM('PRESENT','CORRECTED') NOT NULL DEFAULT 'PRESENT',
 FOREIGN KEY (assignment_id) REFERENCES shift_assignments(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attendance_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 assignment_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 type ENUM('LEAVE','SWAP','CORRECTION') NOT NULL,
 detail TEXT NOT NULL,
 requested_in DATETIME NULL,
 requested_out DATETIME NULL,
 status ENUM('PENDING','APPROVED','REJECTED') NOT NULL DEFAULT 'PENDING',
 reviewed_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(assignment_id) REFERENCES shift_assignments(id),
 FOREIGN KEY(user_id) REFERENCES users(id),
 FOREIGN KEY(reviewed_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cash_shifts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 register_id BIGINT UNSIGNED NOT NULL,
 cashier_id BIGINT UNSIGNED NOT NULL,
 opening_cash DECIMAL(14,2) NOT NULL,
 previous_cash DECIMAL(14,2) NOT NULL DEFAULT 0,
 opening_note TEXT NULL,
 opened_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 closed_at DATETIME NULL,
 closing_cash DECIMAL(14,2) NULL,
 expected_cash DECIMAL(14,2) NULL,
 discrepancy DECIMAL(14,2) NULL,
 closing_note TEXT NULL,
 status ENUM('OPEN','PAUSED','PENDING_APPROVAL','CLOSED') NOT NULL DEFAULT 'OPEN',
 approved_by BIGINT UNSIGNED NULL,
 kept_cash DECIMAL(14,2) NULL,
 deposited_cash DECIMAL(14,2) NULL,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(register_id) REFERENCES registers(id),
 FOREIGN KEY(cashier_id) REFERENCES users(id),
 FOREIGN KEY(approved_by) REFERENCES users(id),
 INDEX(branch_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS cash_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 cash_shift_id BIGINT UNSIGNED NOT NULL,
 direction ENUM('IN','OUT') NOT NULL,
 amount DECIMAL(14,2) NOT NULL,
 reason VARCHAR(250) NOT NULL,
 entered_by BIGINT UNSIGNED NOT NULL,
 approved_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(cash_shift_id) REFERENCES cash_shifts(id),
 FOREIGN KEY(entered_by) REFERENCES users(id),
 FOREIGN KEY(approved_by) REFERENCES users(id),
 CHECK(amount > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(110) NOT NULL UNIQUE,
 sort_order INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 category_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(150) NOT NULL UNIQUE,
 description VARCHAR(500) NULL,
 image_url VARCHAR(500) NULL,
 emoji VARCHAR(12) NULL,
 status ENUM('ACTIVE','PAUSED','DELETED') NOT NULL DEFAULT 'ACTIVE',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(category_id) REFERENCES categories(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_variants (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id BIGINT UNSIGNED NOT NULL,
 size VARCHAR(20) NOT NULL,
 price DECIMAL(12,2) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE(product_id,size),
 FOREIGN KEY(product_id) REFERENCES products(id),
 CHECK(price > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS toppings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 price DECIMAL(12,2) NOT NULL DEFAULT 0,
 active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS branch_products (
 branch_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 available TINYINT(1) NOT NULL DEFAULT 1,
 PRIMARY KEY(branch_id,product_id),
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS branch_variant_prices (
 branch_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL,
 price DECIMAL(12,2) NOT NULL,
 PRIMARY KEY(branch_id,variant_id),
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(variant_id) REFERENCES product_variants(id),
 CHECK(price > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ingredients (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL UNIQUE,
 unit VARCHAR(30) NOT NULL,
 min_quantity DECIMAL(13,3) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS recipes (
 variant_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 PRIMARY KEY(variant_id,ingredient_id),
 FOREIGN KEY(variant_id) REFERENCES product_variants(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 CHECK(quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS topping_recipes (
 topping_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity DECIMAL(12,3) NOT NULL,
 PRIMARY KEY(topping_id,ingredient_id),
 FOREIGN KEY(topping_id) REFERENCES toppings(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 CHECK(quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS branch_inventory (
 branch_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity DECIMAL(14,3) NOT NULL DEFAULT 0,
 avg_cost DECIMAL(14,2) NOT NULL DEFAULT 0,
 PRIMARY KEY(branch_id,ingredient_id),
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 CHECK(quantity >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS suppliers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(150) NOT NULL UNIQUE,
 phone VARCHAR(20) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_receipts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 supplier_id BIGINT UNSIGNED NULL,
 invoice_url VARCHAR(500) NULL,
 source_type ENUM('SUPPLIER','WAREHOUSE') NOT NULL DEFAULT 'SUPPLIER',
 total_cost DECIMAL(14,2) NOT NULL DEFAULT 0,
 status ENUM('DRAFT','PENDING_APPROVAL','CONFIRMED') NOT NULL DEFAULT 'DRAFT',
 created_by BIGINT UNSIGNED NOT NULL,
 approved_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 confirmed_at DATETIME NULL,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(supplier_id) REFERENCES suppliers(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(approved_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_receipt_lines (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 receipt_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity DECIMAL(13,3) NOT NULL,
 unit_cost DECIMAL(14,2) NOT NULL,
 lot_code VARCHAR(100) NULL,
 expires_at DATE NULL,
 FOREIGN KEY(receipt_id) REFERENCES stock_receipts(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 CHECK(quantity > 0), CHECK(unit_cost >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS inventory_lots (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 lot_code VARCHAR(100) NOT NULL,
 expires_at DATE NULL,
 quantity_remaining DECIMAL(13,3) NOT NULL,
 unit_cost DECIMAL(14,2) NOT NULL,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 branch_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity_delta DECIMAL(14,3) NOT NULL,
 movement_type ENUM('RECEIPT','SALE','RESTOCK','WASTE','ADJUSTMENT','TRANSFER_IN','TRANSFER_OUT') NOT NULL,
 reference_type VARCHAR(30) NOT NULL,
 reference_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 FOREIGN KEY(actor_id) REFERENCES users(id),
 INDEX(branch_id,ingredient_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_transfers (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 from_branch_id BIGINT UNSIGNED NOT NULL,
 to_branch_id BIGINT UNSIGNED NOT NULL,
 status ENUM('IN_TRANSIT','RECEIVED') NOT NULL DEFAULT 'IN_TRANSIT',
 created_by BIGINT UNSIGNED NOT NULL,
 received_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(from_branch_id) REFERENCES branches(id),
 FOREIGN KEY(to_branch_id) REFERENCES branches(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(received_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS stock_transfer_lines (
 transfer_id BIGINT UNSIGNED NOT NULL,
 ingredient_id BIGINT UNSIGNED NOT NULL,
 quantity DECIMAL(13,3) NOT NULL,
 PRIMARY KEY(transfer_id,ingredient_id),
 FOREIGN KEY(transfer_id) REFERENCES stock_transfers(id),
 FOREIGN KEY(ingredient_id) REFERENCES ingredients(id),
 CHECK(quantity > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS promotions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(180) NOT NULL,
 code VARCHAR(60) NULL UNIQUE,
 type ENUM('PERCENT','AMOUNT','BOGO','COMBO','FREE_SHIPPING','POINTS_MULTIPLIER') NOT NULL,
 value DECIMAL(12,2) NOT NULL DEFAULT 0,
 min_subtotal DECIMAL(14,2) NOT NULL DEFAULT 0,
 starts_at DATETIME NOT NULL,
 ends_at DATETIME NOT NULL,
 allowed_channel ENUM('ALL','POS','WEB') NOT NULL DEFAULT 'ALL',
 tier_required ENUM('ANY','BRONZE','SILVER','GOLD') NOT NULL DEFAULT 'ANY',
 max_uses INT NULL,
 max_per_customer INT NULL,
 usage_count INT NOT NULL DEFAULT 0,
 auto_apply TINYINT(1) NOT NULL DEFAULT 0,
 stacking TINYINT(1) NOT NULL DEFAULT 0,
 status ENUM('DRAFT','SCHEDULED','ACTIVE','PAUSED','ENDED') NOT NULL DEFAULT 'DRAFT',
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(created_by) REFERENCES users(id),
 CHECK(ends_at > starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS promotion_branches (
 promotion_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(promotion_id,branch_id),
 FOREIGN KEY(promotion_id) REFERENCES promotions(id),
 FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS promotion_products (
 promotion_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(promotion_id,product_id),
 FOREIGN KEY(promotion_id) REFERENCES promotions(id),
 FOREIGN KEY(product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_code VARCHAR(45) NOT NULL UNIQUE,
 branch_id BIGINT UNSIGNED NOT NULL,
 cash_shift_id BIGINT UNSIGNED NULL,
 customer_id BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NULL,
 source ENUM('POS','WEB','KIOSK','DELIVERY') NOT NULL DEFAULT 'POS',
 order_type ENUM('DINE_IN','TAKEAWAY','DELIVERY') NOT NULL DEFAULT 'TAKEAWAY',
 status ENUM('PENDING_PAYMENT','CONFIRMED','PREPARING','READY','DELIVERING','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING_PAYMENT',
 payment_status ENUM('UNPAID','PARTIAL','PAID','REFUNDED') NOT NULL DEFAULT 'UNPAID',
 subtotal DECIMAL(14,2) NOT NULL,
 discount DECIMAL(14,2) NOT NULL DEFAULT 0,
 tax DECIMAL(14,2) NOT NULL DEFAULT 0,
 delivery_fee DECIMAL(14,2) NOT NULL DEFAULT 0,
 total DECIMAL(14,2) NOT NULL,
 promotion_id BIGINT UNSIGNED NULL,
 points_earned INT NOT NULL DEFAULT 0,
 points_redeemed INT NOT NULL DEFAULT 0,
 stock_deducted TINYINT(1) NOT NULL DEFAULT 0,
 queue_number INT NULL,
 guest_name VARCHAR(100) NULL,
 guest_phone VARCHAR(25) NULL,
 delivery_address VARCHAR(350) NULL,
 requested_at DATETIME NULL,
 note VARCHAR(350) NULL,
 cancel_reason VARCHAR(350) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(cash_shift_id) REFERENCES cash_shifts(id),
 FOREIGN KEY(customer_id) REFERENCES users(id),
 FOREIGN KEY(created_by) REFERENCES users(id),
 FOREIGN KEY(promotion_id) REFERENCES promotions(id),
 INDEX(branch_id,status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 variant_id BIGINT UNSIGNED NOT NULL,
 product_name VARCHAR(150) NOT NULL,
 size VARCHAR(20) NOT NULL,
 unit_price DECIMAL(12,2) NOT NULL,
 quantity INT NOT NULL,
 options_json JSON NULL,
 note VARCHAR(250) NULL,
 line_total DECIMAL(14,2) NOT NULL,
 remake_count INT NOT NULL DEFAULT 0,
 FOREIGN KEY(order_id) REFERENCES orders(id),
 FOREIGN KEY(variant_id) REFERENCES product_variants(id),
